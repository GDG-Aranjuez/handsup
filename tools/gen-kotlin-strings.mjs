#!/usr/bin/env node
// Generates the mobile string tables from the web dictionaries so both apps say the same thing.
//   node tools/gen-kotlin-strings.mjs          # rewrite the file
//   node tools/gen-kotlin-strings.mjs --check  # exit 1 if it is out of date (CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { en } from '../web/src/lib/i18n/en.ts';
import { es } from '../web/src/lib/i18n/es.ts';

const out = fileURLToPath(
  new URL('../mobile/composeApp/src/commonMain/kotlin/es/gdgaranjuez/handsup/i18n/GeneratedStrings.kt', import.meta.url),
);
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/\n/g, '\\n');
const table = (name, dict) =>
  `internal val ${name}: Map<String, String> = mapOf(\n${Object.keys(dict)
    .sort()
    .map((k) => `    "${k}" to "${esc(dict[k])}",`)
    .join('\n')}\n)\n`;

const content = `// GENERATED by tools/gen-kotlin-strings.mjs from web/src/lib/i18n/{es,en}.ts. Do not edit.
package es.gdgaranjuez.handsup.i18n

${table('GENERATED_ES', es)}
${table('GENERATED_EN', en)}`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {}
  if (current !== content) {
    console.error('GeneratedStrings.kt is out of date: run node tools/gen-kotlin-strings.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(out, content);
  console.log(`wrote ${out}`);
}
