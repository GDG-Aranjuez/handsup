private fun build(icon: AppIcon): ImageVector {
    val b = ImageVector.Builder(
        name = icon.name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f,
    )
    icon.paths.forEach { d ->
        b.addPath(
            pathData = PathParser().parsePathString(d).toNodes(),
            stroke = SolidColor(Color.Black),
            strokeLineWidth = 2f,
            strokeLineCap = StrokeCap.Round,
            strokeLineJoin = StrokeJoin.Round,
        )
    }
    return b.build()
}

@Composable
fun AppIconView(icon: AppIcon, modifier: Modifier = Modifier, size: Dp = 20.dp, tint: Color = Color.Unspecified) {
    val vector = remember(icon) { build(icon) }
    Icon(vector, contentDescription = null, modifier = modifier.size(size), tint = tint)
}
